import React, { useState } from 'react';
import { EmailInvestigationCase } from '../../types/forensics';
import { Modal } from '../common/Modal';
import { RiskBadge, AuthBadge } from '../common/RiskBadge';
import { Download, Printer, Check, Shield, FileText, CheckCircle2 } from 'lucide-react';

import { apiClient } from '../../api/client';

interface ForensicReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  caseData: EmailInvestigationCase;
  mode?: 'full' | 'iocs';
}

export const ForensicReportModal: React.FC<ForensicReportModalProps> = ({
  isOpen,
  onClose,
  caseData,
  mode = 'full'
}) => {
  const [downloading, setDownloading] = useState(false);
  const [downloadSuccess, setDownloadSuccess] = useState(false);

  const handleDownload = async () => {
    setDownloading(true);
    try {
      await apiClient.generateReport(caseData.caseId, 'PDF');
    } catch {
      // non-blocking
    }
    setTimeout(() => {
      setDownloading(false);
      setDownloadSuccess(true);
      setTimeout(() => setDownloadSuccess(false), 3000);

      // Trigger client-side file download
      const reportBlob = new Blob([
        `================================================================================
TRACE-X - FORENSIC EMAIL INVESTIGATION DOSSIER
CONFIDENTIAL - FOR INTERNAL SOC/INCIDENT RESPONSE USE ONLY
================================================================================

Case Identifier : ${caseData.caseId}
Incident Date   : ${caseData.date}
Assigned Lead   : ${caseData.assignedAnalyst}
Final Verdict   : ${caseData.verdict.toUpperCase()} (Risk Score: ${caseData.riskScore}/100)

EXECUTIVE SUMMARY:
${caseData.summary}

--------------------------------------------------------------------------------
1. TRANSPORT & HEADER TELEMETRY
--------------------------------------------------------------------------------
From         : ${caseData.from}
Reply-To     : ${caseData.replyTo}
Return-Path  : ${caseData.returnPath}
Message-ID   : ${caseData.messageId}
Received     : ${caseData.receivedTime}

--------------------------------------------------------------------------------
2. CRYPTOGRAPHIC & PROTOCOL AUTHENTICATION
--------------------------------------------------------------------------------
SPF Status   : ${caseData.auth.spf.status} (${caseData.auth.spf.summary})
DKIM Status  : ${caseData.auth.dkim.status} (${caseData.auth.dkim.summary})
DMARC Status : ${caseData.auth.dmarc.status} (${caseData.auth.dmarc.summary})

--------------------------------------------------------------------------------
3. PRIMARY INFRASTRUCTURE & ATTRIBUTION
--------------------------------------------------------------------------------
Originating IP : ${caseData.primaryInfrastructure.ip}
Reverse DNS    : ${caseData.primaryInfrastructure.reverseDns}
ASN            : ${caseData.primaryInfrastructure.asn}
ISP            : ${caseData.primaryInfrastructure.isp}
Location       : ${caseData.primaryInfrastructure.city}, ${caseData.primaryInfrastructure.country}
Hosting Type   : ${caseData.primaryInfrastructure.hosting}

--------------------------------------------------------------------------------
4. INDICATORS OF COMPROMISE (IOCS)
--------------------------------------------------------------------------------
[Domains]
${caseData.iocs.domains.map(d => ` - ${d}`).join('\n')}

[IP Addresses]
${caseData.iocs.ips.map(ip => ` - ${ip}`).join('\n')}

[URLs]
${caseData.iocs.urls.map(u => ` - ${u}`).join('\n')}

[Attachments]
${caseData.iocs.attachments.map(a => ` - ${a.filename} (SHA256: ${a.sha256})`).join('\n')}

--------------------------------------------------------------------------------
5. RECOMMENDED NEXT STEPS
--------------------------------------------------------------------------------
${caseData.recommendedActions.map(r => ` [Step ${r.id}] [${r.priority}] ${r.action}`).join('\n')}

================================================================================
Generated by TRACE-X Forensics Engine v2.4
`
      ], { type: 'text/plain;charset=utf-8' });

      const link = document.createElement('a');
      link.href = URL.createObjectURL(reportBlob);
      link.download = `${caseData.caseId}_Forensic_Report.txt`;
      link.click();
    }, 800);
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title={mode === 'full' ? 'Forensic Investigation Dossier' : 'IOC Export Package'}
      subtitle={`${caseData.caseId} • Generated by TRACE-X`}
      maxWidth="4xl"
    >
      <div className="space-y-6">
        {/* Action bar */}
        <div className="flex items-center justify-between bg-slate-50 p-3 rounded-xl border border-slate-200">
          <div className="flex items-center gap-2">
            <FileText className="w-4 h-4 text-blue-600" />
            <span className="text-xs font-semibold text-slate-700">
              Audit-Ready SOC Incident Report
            </span>
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={() => window.print()}
              className="inline-flex items-center gap-1 px-3 py-1.5 rounded-lg border border-slate-200 bg-white text-xs font-semibold text-slate-700 hover:bg-slate-100"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>Print</span>
            </button>
            <button
              onClick={handleDownload}
              disabled={downloading}
              className="inline-flex items-center gap-1.5 px-4 py-1.5 rounded-lg bg-blue-600 text-xs font-semibold text-white hover:bg-blue-700 shadow-sm transition-all"
            >
              {downloadSuccess ? <Check className="w-3.5 h-3.5" /> : <Download className="w-3.5 h-3.5" />}
              <span>{downloadSuccess ? 'Downloaded!' : downloading ? 'Generating...' : 'Download Report'}</span>
            </button>
          </div>
        </div>

        {/* Dossier Document Container */}
        <div className="max-h-[65vh] overflow-y-auto pr-2 space-y-6 text-xs text-slate-800 font-sans border border-slate-200 p-6 rounded-xl bg-white shadow-inner">
          {/* Header Banner */}
          <div className="border-b-2 border-slate-900 pb-4 flex justify-between items-start">
            <div>
              <div className="flex items-center gap-2">
                <div className="p-1 rounded bg-blue-600 text-white">
                  <Shield className="w-4 h-4" />
                </div>
                <span className="text-sm font-bold uppercase tracking-wider text-slate-900">
                  TRACE-X Forensics Lab
                </span>
              </div>
              <h1 className="text-xl font-extrabold text-slate-900 mt-2">
                Cyber Incident Triage Report: {caseData.caseId}
              </h1>
              <p className="text-slate-500 text-[11px] mt-0.5">
                Timestamp: {caseData.date} • Analyst: {caseData.assignedAnalyst}
              </p>
            </div>
            <div className="text-right">
              <RiskBadge verdict={caseData.verdict} size="lg" />
              <div className="text-xs font-mono font-bold text-slate-600 mt-1">
                Score: {caseData.riskScore}/100
              </div>
            </div>
          </div>

          {/* Executive Summary */}
          <div className="space-y-1.5">
            <h3 className="text-xs font-bold uppercase tracking-wider text-slate-900">
              Executive Summary
            </h3>
            <p className="text-slate-700 leading-relaxed bg-slate-50 p-3 rounded-lg border border-slate-100">
              {caseData.summary}
            </p>
          </div>

          {/* Email Info & Transport */}
          <div className="grid grid-cols-2 gap-4">
            <div className="p-3 bg-slate-50 rounded-lg border border-slate-100 space-y-1">
              <span className="text-[10px] font-bold uppercase text-slate-400">Header Information</span>
              <div><strong>From:</strong> <span className="font-mono text-slate-700">{caseData.from}</span></div>
              <div><strong>Reply-To:</strong> <span className="font-mono text-slate-700">{caseData.replyTo}</span></div>
              <div><strong>Subject:</strong> <span>{caseData.subject}</span></div>
            </div>
            <div className="p-3 bg-slate-50 rounded-lg border border-slate-100 space-y-1">
              <span className="text-[10px] font-bold uppercase text-slate-400">Authentication Summary</span>
              <div className="flex items-center gap-2"><span>SPF:</span> <AuthBadge status={caseData.auth.spf.status} /></div>
              <div className="flex items-center gap-2"><span>DKIM:</span> <AuthBadge status={caseData.auth.dkim.status} /></div>
              <div className="flex items-center gap-2"><span>DMARC:</span> <AuthBadge status={caseData.auth.dmarc.status} /></div>
            </div>
          </div>

          {/* Infrastructure */}
          <div className="p-3 bg-slate-50 rounded-lg border border-slate-100 space-y-1">
            <span className="text-[10px] font-bold uppercase text-slate-400">Flagged Infrastructure</span>
            <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 text-[11px] mt-1">
              <div><span className="text-slate-500">IP:</span> <span className="font-mono font-bold">{caseData.primaryInfrastructure.ip}</span></div>
              <div><span className="text-slate-500">Country:</span> <span>{caseData.primaryInfrastructure.country}</span></div>
              <div><span className="text-slate-500">ASN:</span> <span>{caseData.primaryInfrastructure.asn}</span></div>
              <div><span className="text-slate-500">Hosting:</span> <span>{caseData.primaryInfrastructure.hosting}</span></div>
            </div>
          </div>

          {/* IOCs */}
          <div className="space-y-2">
            <h3 className="text-xs font-bold uppercase tracking-wider text-slate-900">
              Extracted Indicators of Compromise (IOCs)
            </h3>
            <div className="font-mono text-[11px] bg-slate-900 text-slate-200 p-3 rounded-lg space-y-2">
              <div>
                <span className="text-blue-400 font-bold"># Domains:</span>
                {caseData.iocs.domains.map((d, i) => <div key={i} className="pl-3">{d}</div>)}
              </div>
              <div>
                <span className="text-amber-400 font-bold"># IPs:</span>
                {caseData.iocs.ips.map((ip, i) => <div key={i} className="pl-3">{ip}</div>)}
              </div>
              <div>
                <span className="text-red-400 font-bold"># URLs:</span>
                {caseData.iocs.urls.map((u, i) => <div key={i} className="pl-3">{u}</div>)}
              </div>
              <div>
                <span className="text-emerald-400 font-bold"># Payload Hashes:</span>
                {caseData.iocs.attachments.map((a, i) => <div key={i} className="pl-3">{a.filename}: {a.sha256}</div>)}
              </div>
            </div>
          </div>

          {/* Recommended Next Steps */}
          <div className="space-y-1.5">
            <h3 className="text-xs font-bold uppercase tracking-wider text-slate-900">
              Remediation Playbook
            </h3>
            <div className="space-y-1">
              {caseData.recommendedActions.map((rec) => (
                <div key={rec.id} className="flex items-start gap-2 text-[11px] text-slate-700">
                  <span className="font-bold text-slate-400">{rec.id}.</span>
                  <span>[{rec.priority}] {rec.action}</span>
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>
    </Modal>
  );
};
